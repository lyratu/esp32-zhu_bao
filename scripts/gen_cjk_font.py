"""Generate a compact bitmap font header for the OLED UI.

Two things are produced:

1. A 12x12 CJK/Hanzi bitmap table for exactly the characters this UI uses.
   Only the glyphs actually referenced are included, which keeps the firmware
   small (a full CJK font is megabytes; this is a few hundred bytes).

2. Nothing else - the ASCII half keeps using the existing public-domain 8x8
   font (font8x8_basic.h), so English text stays crisp and unchanged.

Run:  python scripts/gen_cjk_font.py
Out:  main/display/font_cjk.h

The character set is extracted automatically from the C string literals in
ui.c, so the font can never drift out of sync with the screens: add a string
to ui.c, re-run this script, done. A character that somehow slips through
renders as a hollow box at runtime instead of silently vanishing.
"""
import os
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUT = str(PROJECT_ROOT / "main/display/font_cjk.h")
UI_C = str(PROJECT_ROOT / "main/display/ui.c")
FONT_PATH = r"C:/Windows/Fonts/simhei.ttf"   # 黑体: bold strokes read well at 12px
SIZE = 12          # 12x12 cell; drawn at native pixel grid for sharpness


# Characters that reach the panel at RUNTIME and therefore never appear in a
# ui.c string literal. The device name comes from the Bambu cloud
# (bambu_get_devices) and can contain arbitrary Hanzi; a name character that
# is missing here renders as a hollow box. Extend this list whenever a name
# shows hollow boxes on the panel.
EXTRA_CHARS = set("雯雯的打印机")


def collect_chars():
    """Every non-ASCII character appearing in a ui.c string literal, plus the
    runtime-sourced characters in EXTRA_CHARS."""
    src = open(UI_C, encoding="utf-8").read()
    lits = re.findall(r'"((?:[^"\\]|\\.)*)"', src)
    chars = set(EXTRA_CHARS)
    for lit in lits:
        for ch in lit:
            if ord(ch) > 0x7F:
                chars.add(ch)
    if not chars:
        raise SystemExit("no non-ASCII characters found in %s" % UI_C)
    return chars


def render(ch):
    """Render one glyph into a SIZE x SIZE 1-bit image."""
    img = Image.new("1", (SIZE, SIZE), 0)
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(FONT_PATH, SIZE - 1)
    # Centre the glyph in the cell. anchor="mm" uses the font's own metrics,
    # which is more reliable than manual bbox maths for CJK.
    d.text((SIZE // 2, SIZE // 2), ch, font=font, fill=1, anchor="mm")
    return img


def rows_to_bytes(img):
    """Pack the image into SIZE uint16 rows (bit x = column x, MSB-first)."""
    px = img.load()
    out = []
    for y in range(SIZE):
        v = 0
        for x in range(SIZE):
            if px[x, y]:
                v |= 1 << x
        out.append(v)
    return out


def main():
    unique = sorted(collect_chars())
    lines = [
        "#pragma once",
        "/* Generated by scripts/gen_cjk_font.py - do not edit by hand.",
        " *",
        " * %dx%d bitmap glyphs for the Hanzi/punctuation this UI shows." % (SIZE, SIZE),
        " * Only the characters below are stored, so the table stays small.",
        " * Lookup is a binary search over a sorted UTF-8 codepoint table.",
        " *",
        " * Any character not in this table renders as a hollow box, which",
        " * makes a missing glyph obvious on the panel instead of silent. */",
        "#include <stdint.h>",
        "",
        "#define CJK_GLYPH_W %d" % SIZE,
        "#define CJK_GLYPH_H %d" % SIZE,
        "",
        "typedef struct {",
        "    uint32_t cp;                 /* UTF-8 codepoint */",
        "    uint16_t rows[%d];           /* one entry per pixel row, bit x = column */" % SIZE,
        "} cjk_glyph_t;",
        "",
        "static const cjk_glyph_t cjk_glyphs[] = {",
    ]

    for ch in unique:
        img = render(ch)
        rows = rows_to_bytes(img)
        hexrows = ", ".join("0x%04X" % r for r in rows)
        lines.append("    { 0x%04X, { %s } },  /* %s */"
                     % (ord(ch), hexrows, ch))

    lines += [
        "};",
        "",
        "#define CJK_GLYPH_COUNT (sizeof(cjk_glyphs) / sizeof(cjk_glyphs[0]))",
        "",
    ]

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print("wrote %s" % OUT)
    print("glyphs: %d (%.1f KB of bitmap data)"
          % (len(unique), len(unique) * (SIZE * 2 + 4) / 1024.0))


if __name__ == "__main__":
    main()

"""Regenerate the pinned cloud trust anchors.

The Bambu cloud uses a DIFFERENT CA per region, so one pinned root is not
enough:

    api.bambulab.cn  ->  GlobalSign GCC R3 DV TLS CA 2020
                         root: GlobalSign Root CA - R3
    api.bambulab.com ->  DigiCert Encryption Everywhere DV TLS CA - G2
                         root: DigiCert Global Root G2

The ESP-IDF runtime certificate bundle never matches either chain on this
board, so both roots are extracted from cacrt_all.pem and written into a
single header as C string literals. See net/bambu_api.c for how they are
selected per host.

Run:  python scripts/gen_root_ca.py
"""
import re
import subprocess
from pathlib import Path

BUNDLE = r"D:/esp/v6.1/esp-idf/components/mbedtls/esp_crt_bundle/cacrt_all.pem"
OUT = str(Path(__file__).resolve().parents[1] / "main/net/cloud_roots.h")

# (symbol name, subject substring to match, comment)
WANTED = [
    ("GLOBALSIGN_ROOT_R3_PEM", "GlobalSign Root CA - R3",
     "api.bambulab.cn  (GlobalSign GCC R3 DV TLS CA 2020)"),
    ("DIGICERT_GLOBAL_ROOT_G2_PEM", "DigiCert Global Root G2",
     "api.bambulab.com (DigiCert Encryption Everywhere DV TLS CA - G2)"),
]

text = open(BUNDLE).read()
certs = re.findall(
    r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", text, re.S)


def cert_subject(c):
    r = subprocess.run(["openssl", "x509", "-noout", "-subject"],
                       input=c, capture_output=True, text=True)
    return r.stdout


def c_literal(pem_lines):
    """Emit escaped double-quoted C literals.

    Do NOT use Python repr(): it emits single quotes, which become
    multi-character literals and fail the build with -Werror.
    """
    out = []
    for line in pem_lines:
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "' + escaped + '\\n"')
    return out


found = {}
for c in certs:
    subj = cert_subject(c).replace("\n", " ")
    for sym, want, _ in WANTED:
        if sym in found:
            continue
        # Match the whole subject line, not just the CN: the GlobalSign root
        # has CN=GlobalSign with the distinguishing name in the OU, and
        # matching "GlobalSign Root CA - R3" anywhere would also hit R6.
        if want in subj:
            found[sym] = c.strip()

missing = [s for s, _, _ in WANTED if s not in found]
assert not missing, "certificate(s) not found in bundle: %s" % missing

out = ["#pragma once",
       "/* Pinned trust anchors for the Bambu cloud.",
       " *",
       " * Generated by scripts/gen_root_ca.py from the ESP-IDF bundle",
       " * (cacrt_all.pem). Do not edit by hand.",
       " *",
       " * The two regions do NOT share a CA, so both roots are needed:",
       ]

for sym, want, note in WANTED:
    out.append(" *   %-28s %s" % (sym.replace("_PEM", ""), note))
out += [" *",
        " * The runtime esp_crt_bundle lookup fails on both chains on this",
        " * hardware, hence the explicit pinning. */",
        ""]

for sym, want, note in WANTED:
    pem = found[sym]
    out.append("/* %s" % want)
    out.append(" * %s */" % note)
    out.append("static const char %s[] =" % sym)
    out += c_literal(pem.splitlines())
    out.append("    ;")
    out.append("")

with open(OUT, "w", newline="\n") as f:
    f.write("\n".join(out))

for sym, want, _ in WANTED:
    print("wrote %-28s %s" % (sym, want))
print("->", OUT)
